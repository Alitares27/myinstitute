CREATE TABLE IF NOT EXISTS baptism_agendas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheduled_at timestamp without time zone NOT NULL,
    friend varchar(150) NOT NULL,
    opening_hymn varchar(150) NOT NULL DEFAULT '',
    opening_prayer_id integer REFERENCES users(id) ON DELETE SET NULL,
    baptism_talk_id integer REFERENCES users(id) ON DELETE SET NULL,
    baptism_id integer REFERENCES users(id) ON DELETE SET NULL,
    witness_one_id integer REFERENCES users(id) ON DELETE SET NULL,
    witness_two_id integer REFERENCES users(id) ON DELETE SET NULL,
    holy_ghost_talk_id integer REFERENCES users(id) ON DELETE SET NULL,
    confirmation_id integer REFERENCES users(id) ON DELETE SET NULL,
    closing_hymn varchar(150) NOT NULL DEFAULT '',
    closing_prayer_id integer REFERENCES users(id) ON DELETE SET NULL
);
